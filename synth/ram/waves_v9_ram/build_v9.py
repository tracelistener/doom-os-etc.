def retain(seconds, scale):
    """Per-sample retention factor of a one-pole segment."""
    return math.exp(-1 / max(seconds / scale * SR, 1e-9))


def preset_rows():
    rows = []
    for name, amp, filt in PRESETS:
        if amp is None:
            rows.append((name, [1.0] * 8 + [0.0, 0.0, 2.0, 1.0, 1.0], 0))
            continue
        a, d, s, r = amp
        values = [retain(a, 1.466), retain(d, 6.908), s, retain(r, 6.908)]
        if filt:
            base, depth, fa, fd, fs, fr, k, drive, gain = filt
            values += [retain(fa, 1.466), retain(fd, 6.908), fs, retain(fr, 6.908), base, depth, k, drive, gain]
        else:
            values += [1.0, 1.0, 0.0, 1.0, 0.0, 0.0, 2.0, 1.0, 1.0]
        rows.append((name, values, 1 if filt else 0))
    return rows


def cfloat(v):
    text = '%.9g' % v
    return (text if '.' in text or 'e' in text else text + '.0') + 'f'


def write_preset_header():
    lines = ['/* Generated by build_v9.py: ENV presets, 48 kHz retention factors. */',
             'typedef struct {',
             '    float ra, rd, sus, rr;              /* volume: attack, decay, sustain, release */',
             '    float fra, frd, fsus, frr;          /* filter envelope */',
             '    float base, amount, k, drive, gain; /* cutoff = note * 2^(base + amount*env) */',
             '    int filter;',
             '} preset_t;',
             'static const preset_t presets[10] = {']
    for name, values, filt in preset_rows():
        lines.append('    {' + ', '.join(cfloat(v) for v in values) + f', {filt}}},  /* {name} */')
    lines.append('};')
    names = ', '.join('"%s"' % name for name, _, _ in PRESETS)
    lines.append(f'static const char preset_names[10][6] = {{{names}}};')
    text = '\n'.join(lines) + '\n'
    (HERE / 'env_presets.h').write_text(text, encoding='ascii', newline='\n')
    return hashlib.sha256(text.encode('ascii')).hexdigest()


def read_module(data, link_base, limit):
    """Allocated sections (BSS as zeros, copied at boot) and every global symbol."""
    if data[:7] != b'\x7fELF\x01\x01\x01' or struct.unpack_from('<H', data, 18)[0] != 40:
        raise ValueError('expected little-endian ARM ELF32')
    shoff = struct.unpack_from('<I', data, 32)[0]
    shsize, count, _ = struct.unpack_from('<3H', data, 46)
    sections = [struct.unpack_from('<10I', data, shoff + i * shsize) for i in range(count)]
    syms, blocks, end = {}, [], link_base
    for name, kind, flags, addr, off, size, link, info, align, entsize in sections:
        if flags & 2 and size:
            if not link_base <= addr < limit or addr + size > limit:
                raise ValueError('unexpected allocated ELF address')
            blocks.append((addr, bytes(size) if kind == 8 else data[off:off + size]))
            end = max(end, addr + size)
        if kind == 2:
            strings = sections[link]
            text = data[strings[4]:strings[4] + strings[5]]
            for at in range(off, off + size, entsize):
                n, value, _, sym_info = struct.unpack_from('<3IB', data, at)
                label = text[n:].split(b'\0')[0].decode('ascii')
                if sym_info >> 4 == 1 and label:          # global
                    syms[label] = value
    out = bytearray(end - link_base)
    for addr, block in blocks:
        out[addr - link_base:addr - link_base + len(block)] = block
    return bytes(out), syms


