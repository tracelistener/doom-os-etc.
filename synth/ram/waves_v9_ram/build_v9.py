def compile_arm():
    folder = HERE / 'build' / 'ram'
    folder.mkdir(parents=True, exist_ok=True)
    if LINKER == v3.LINKER:
        raise ValueError('v3 linker script changed')
    (folder / 'waves.ld').write_text(LINKER.format(base=v6b.LINK_BASE), encoding='ascii', newline='\n')
    subprocess.run([str(v3.ZIG), 'cc', '-target', 'thumb-freestanding-eabihf',
                    '-mcpu=cortex_m7+vfp4d16', '-mfpu=vfpv4-d16', '-mfloat-abi=hard', *v4b.COMMON,
                    '-nostdlib', '-Wl,--no-undefined', '-Wl,--build-id=none', '-Wl,-e,wave_output',
                    '-Wl,-T,' + str(folder / 'waves.ld'), '-I', str(HERE), '-I', str(ROOT / 'waves_v8_ram'), str(ROOT / 'waves_v8_ram' / 'waves.c'),
                    str(HERE / 'env.c'), '-o', str(folder / 'waves.elf')],
                   check=True, cwd=HERE, env=v4b.ZIG_ENV)
    elf = (folder / 'waves.elf').read_bytes()
    blob, symbols = read_module(elf, v6b.LINK_BASE, v6b.NONCACHE)
    needed = {'wave_output', 'wave_name', 'wave_eval', 'wave_core', 'env_stage', 'env_name',
              'note_event', 'export_mix', 'freq_get', 'freq_event', 'display_voice', 'display_slot',
              'midi_event', 'kb_pad_note', 'kb_in_scale', 'kb_pad_rel',
              'env_fast', 'env_quick', 'env_slot', 'env_restart', 'env_age', 'stolen_valid'}
    if not needed <= set(symbols):
        raise ValueError(f'module exports missing: {sorted(needed - set(symbols))}')
    (folder / 'waves.bin').write_bytes(blob)
    return blob, {k: symbols[k] for k in sorted(needed)}


SOUNDING, SELECTED = 'ldrb.w r0, [r0, #0x70]', 'ldrb.w r0, [r0, #0x71]'

# Stock UI code that read the sounding TYPE (+0x70). The oscillator only swaps
# it in after a ~4 ms crossfade, and never while a voice fades out, so the TYPE
# knob stepped from a stale value and the screen lagged. They read the selected
# TYPE (+0x71) instead; audio code keeps reading the sounding one.
UI_TYPE_READS = [
    (0x80019FA0, 'r0', 'r4'),   # setter: TYPE unchanged? / DUTY default when leaving noise
    (0x80019FC0, 'r0', 'r4'),   # setter: is DUTY used by this TYPE
    (0x8002046C, 'r0', 'r0'),   # getter: TYPE (the knob steps from it)
    (0x80020474, 'r1', 'r0'),   # getter: FREQ
    (0x800204A4, 'r1', 'r0'),   # getter: DUTY
    (0x80131BA4, 'r0', 'r0'),   # label: DUTY
    (0x80131CC8, 'r2', 'r0'),   # value text: FREQ
    (0x80131D98, 'r1', 'r0'),   # value text: DUTY
    (0x801326A0, 'r0', 'r0'),   # range: FREQ
    (0x801326BC, 'r0', 'r0'),   # range: DUTY
    (0x8015C5F8, 'r1', 'r0'),   # START/END allowed
    (0x8002B94C, 'r2', 'r0'),   # START/END allowed (page 66)
]


def gate_sources(symbols):
    """v7's gates reading the selected TYPE; FREQ_LABEL's slot ends at the ENV name bridge."""
    osc, name, freq = v7b.gate_sources(symbols)
    if not name[2].strip().startswith(SOUNDING) or not freq[2].strip().startswith(SOUNDING):
        raise ValueError('v6 name/label gate source changed')
    name = (name[0], name[1], name[2].replace(SOUNDING, SELECTED, 1))
    freq = (freq[0], ENV_NAME, freq[2].replace(SOUNDING, SELECTED, 1))
    return [osc, name, freq,
            (ENV_NAME, ENV_NAME + 0x40, f'''
                ldr r0, [r0, #0x10]
                mov r1, r4
                {call(symbols['env_name'])}
                {jump(0x80131C78)}
            '''),
            (FREQ_TEXT, FREQ_TEXT + 0x40, f'''
                ldrb.w r2, [r0, #0x71]
                cmp r2, #31
                bhi no_note
                push {{r1, r2}}
                {call(symbols['display_voice'])}
                pop {{r1, r2}}
                {jump(0x80131CD2)}
            no_note:
                {jump(0x80131E20)}
            ''')]


v6b.gate_sources = gate_sources


def stock_bytes(address, size):
    stock = STOCK.read_bytes()
    return stock[v2.old_high_file(address):v2.old_high_file(address) + size]


def replace(image, address, expected, replacement):
    off = v3.file_offset(image, address, len(expected))
    if image[off:off + len(expected)] != expected:
        raise ValueError(f'unexpected bytes at {address:#x}')
    if len(replacement) > len(expected):
        raise ValueError(f'patch at {address:#x} is too long')
    out = bytearray(image)
    out[off:off + len(expected)] = replacement.ljust(len(expected), b'\0')
    return bytes(out)


def release_sources(symbols):
    """(release-fixed all-stop engine as in the base image, v9 version marking env_fast)."""
    fixed = v4.release_source().replace('        str r0, [r4, #0x4c]\n',
                                        '        mvn r0, #0xc7\n        str r0, [r4, #0x4c]\n')
    head = 'push {r4-r6, lr}\n'
    if fixed.count('str r0, [r4, #0x4c]') != 1 or head not in fixed:
        raise ValueError('v4 release source changed')
    marks = (load('r0', symbols['env_fast']) + 'movs r1, #1\n' +
             ''.join(f'strb r1, [r0, #{i}]\n' for i in range(4)))
    return fixed, fixed.replace(head, head + marks, 1)


def check_stage_entry(image):
    """Nothing may branch into the bytes the ENV stage call replaces, except its start."""
    md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_THUMB | capstone.CS_MODE_MCLASS)
    lo, hi = 0x80007700, ENV_STAGE_SITE
    off = v3.file_offset(image, lo, hi - lo)
    for ins in md.disasm(image[off:off + (hi - lo)], lo):
        if ins.mnemonic.startswith(('b', 'cb')) and ins.op_str.startswith('#'):
            target = int(ins.op_str.split('#')[-1], 16)
            if ENV_STAGE_SITE < target < ENV_STAGE_SITE + 0x14:
                raise ValueError(f'branch into the ENV stage call at {ins.address:#x}')


def build_image(module, symbols, base=None):
    if base is None:
        base = v3.BASE.read_bytes()
    image, info = v6b.build_image(base, module, symbols)
    image = v5b.apply_extra(image)
    size = v4.PARAM_ENGINE - v4.NOTE_ENGINE
    old_note = v3.asm(v7b.note_sources()[0], v4.NOTE_ENGINE).ljust(size, b'\0')
    image = replace(image, v4.NOTE_ENGINE, old_note, v3.asm(jump(symbols['note_event']), v4.NOTE_ENGINE))
    size = v4.CAPTURE_INIT - v4.RELEASE_ENGINE
    old_release, new_release = release_sources(symbols)
    image = replace(image, v4.RELEASE_ENGINE, v3.asm(old_release, v4.RELEASE_ENGINE).ljust(size, b'\0'),
                    v3.asm(new_release, v4.RELEASE_ENGINE))
    check_stage_entry(image)
    stage = v3.asm(f'''
        mov r0, r4
        mov r1, r5
        {call(symbols['env_stage'])}
        vpop {{d8-d12}}
        pop {{r4-r6, pc}}
    ''', ENV_STAGE_SITE)
    image = replace(image, ENV_STAGE_SITE, stock_bytes(ENV_STAGE_SITE, len(stage)), stage)
    text = v3.asm(jump(ENV_NAME) + 'nop\n', ENV_TEXT_SITE)
    image = replace(image, ENV_TEXT_SITE, stock_bytes(ENV_TEXT_SITE, len(text)), text)
    v9_hooks = [[v4.NOTE_ENGINE, len(old_note)], [v4.RELEASE_ENGINE, size],
                [ENV_STAGE_SITE, len(stage)], [ENV_TEXT_SITE, len(text)]]
    for address, rt, rn in UI_TYPE_READS:
        old = v3.asm(f'ldrb.w {rt}, [{rn}, #0x70]', address)
        if stock_bytes(address, len(old)) != old:
            raise ValueError(f'stock TYPE read changed at {address:#x}')
        image = replace(image, address, old, v3.asm(f'ldrb.w {rt}, [{rn}, #0x71]', address))
        v9_hooks.append([address, len(old)])
    # REC: the chord snapshot takes the selected TYPE, not voice 0's sounding one.
    export = v4.export_source()
    chosen = export.replace('ldrb.w r0, [r4, #0x70]', 'ldrb.w r0, [r4, #0x71]', 1)
    old_export, new_export = v3.asm(export, v4.EXPORT_ENGINE), v3.asm(chosen, v4.EXPORT_ENGINE)
    if chosen == export or len(old_export) != len(new_export):
        raise ValueError('v4 export source changed')
    image = replace(image, v4.EXPORT_ENGINE, old_export, new_export)
    v9_hooks.append([v4.EXPORT_ENGINE, len(old_export)])
    # REC mixer -> export_mix (same mix, plus the one-shot end fade). Entered by a
    # jump from the oscillator gate, so sp and r10/r11 are still the exporter's.
    size = v4.OSC_GATE - v4.EXPORT_SAMPLE
    old_mix = v3.asm(v4.sample_source(), v4.EXPORT_SAMPLE).ljust(size, b'\0')
    mix = v3.asm('ldr r2, [sp, #4]\nmov r0, r10\nmov r1, r11\n' + jump(symbols['export_mix']),
                 v4.EXPORT_SAMPLE)
    image = replace(image, v4.EXPORT_SAMPLE, old_mix, mix)
    v9_hooks.append([v4.EXPORT_SAMPLE, size])
    # FREQ follows the latest note: getter case, readout text, and the knob's transpose.
    get_old = (v3.asm('ldrb.w r1, [r0, #0x71]\ncmp r1, #0x1f', FREQ_GET_SITE) +
               stock_bytes(FREQ_GET_SITE + 6, 6))           # bhi 0x800204b4; ldr r0, [r0, #0x5c]; bx lr
    image = replace(image, FREQ_GET_SITE, get_old, v3.asm(jump(symbols['freq_get']) + 'nop\n', FREQ_GET_SITE))
    text_old = (v3.asm('ldrb.w r2, [r0, #0x71]\ncmp r2, #31', FREQ_TEXT_SITE) +
                stock_bytes(FREQ_TEXT_SITE + 6, 4))         # bhi.w 0x80131e20
    image = replace(image, FREQ_TEXT_SITE, text_old, v3.asm(jump(FREQ_TEXT), FREQ_TEXT_SITE))
    size = v4.TUNE_RESET - v4.FREQ_ENGINE
    old_freq = v3.asm(v4.freq_source(), v4.FREQ_ENGINE).ljust(size, b'\0')
    image = replace(image, v4.FREQ_ENGINE, old_freq, v3.asm(jump(symbols['freq_event']), v4.FREQ_ENGINE))
    v9_hooks += [[FREQ_GET_SITE, len(get_old)], [FREQ_TEXT_SITE, len(text_old)], [v4.FREQ_ENGINE, size]]

    def stock_span(address, end, source):
        nonlocal image
        new = v3.asm(source, address)
        if len(new) > end - address or (end - address - len(new)) % 2:
            raise ValueError(f'patch at {address:#x} does not fit')
        # Keystone mis-encodes some absolute branches (beq.w #0x8015bfa6 came out as
        # beq.w #0x800b8036): every direct branch must hit a target named in the source.
        named = {int(t, 16) for t in re.findall(r'#(0x[0-9a-fA-F]+)', source)}
        md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_THUMB | capstone.CS_MODE_MCLASS)
        for ins in md.disasm(new, address):
            if ins.mnemonic.startswith(('b', 'cb')) and ins.op_str.split(', ')[-1].startswith('#'):
                target = int(ins.op_str.split('#')[-1], 16)
                if target not in named and not address <= target < address + len(new):
                    raise ValueError(f'patch at {address:#x}: branch at {ins.address:#x} to {target:#x}')
        image = replace(image, address, stock_bytes(address, end - address),
                        new + b'\0\xbf' * ((end - address - len(new)) // 2))
        v9_hooks.append([address, end - address])

    # Scale pads: the pad helpers used by the pad lights, and the SG page's own
    # note-on/note-off pad maths, all take kb_pad_note's note.
    for address, symbol in ((0x80030C88, 'kb_pad_note'), (0x80030FA8, 'kb_in_scale'),
                            (0x80030E98, 'kb_pad_rel')):
        stock_span(address, address + 12, jump(symbols[symbol]) + 'nop\n')
    stock_span(0x8015C070, 0x8015C0C8,           # note-on; off the SG page, stock's out-of-scale skip
               'mov r0, r4\n' + call(symbols['kb_pad_note']) + 'mov r6, r0\nmov r0, r4\n' +
               call(symbols['kb_in_scale']) + 'cmp r0, #0\nbeq #0x8015bfa6\nb #0x8015c0c8\n')
    stock_span(0x8015C4D0, 0x8015C4F0,           # note-off: same note, then the v2 dispatcher call
               'mov r0, r4\n' + call(symbols['kb_pad_note']) +
               'mov r1, r0\nmovs r2, #0\nmovs r3, #1\nstr r4, [sp]\n')
    # MIDI IN: the dispatcher's voice-0 call goes to the four-voice MIDI engine.
    stock_span(0x8005A694, 0x8005A6A4, 'uxtb r2, r5\nmov r3, r6\n' + call(symbols['midi_event']) + 'nop\n')
    # REC with notes held: fade the voices (all-stop) instead of cutting them.
    old_init, new_init = v4.capture_init_source(), v4.capture_init_source().replace(
        v4.call(v2.INIT_ALL_WRAPPER), v4.call(v4.RELEASE_ENGINE))
    if old_init == new_init:
        raise ValueError('v4 capture/init source changed')
    size = v4.LED_MATCH - v4.CAPTURE_INIT
    image = replace(image, v4.CAPTURE_INIT, v3.asm(old_init, v4.CAPTURE_INIT).ljust(size, b'\0'),
                    v3.asm(new_init, v4.CAPTURE_INIT))
    v9_hooks.append([v4.CAPTURE_INIT, size])
    info['hooks'] += [[a, len(v3.asm(b, a))] for a, b, _ in v5b.EXTRA] + v9_hooks
    info['v9_hooks'] = v9_hooks
    return image, info


