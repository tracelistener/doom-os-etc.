"""Build Sound Generator v9 (RAM, OS pool untouched): v8 + real envelopes,
filter envelopes and voice stealing.

- ENV keeps its ten values. OFF is stock. Roland's nine attack-only shapes
  (A..C2, at most one waveform cycle long) become nine timed presets: five
  volume envelopes and four that also sweep a resonant low-pass filter.
  They work on every wave, stock included, on all four voices and in REC export.
- Released notes ring out for the preset's release time. All-stop still cuts
  everything with the stock ~8 ms fade, long releases included.
- A fifth note no longer gets dropped: it takes the oldest fading voice, else
  the oldest held one; v9.5 fades it out in 2.8 ms before a fresh start. A 30 ms
  no-audio timeout uses the older in-place de-click fallback. The later note-off is
  ignored, so it cannot release another note.
Everything else is v8: the 17 waves with raw DUTY grit, loudness tables, quiet
Pulse/Noise, the OCT note-off fallback, the layout in unused SDRAM.
v9.1-v9.4 add: REC and TYPE-display fixes, the REC end fade, the FREQ readout
following the latest note, scale pads, MIDI IN on all four voices, and a fade
instead of a cut when REC starts with notes held (see README below).

Archived build helper; in this public repository use synth/build_v9.py.
Its wrapper supplies the official stock input, verified base and compiler.
"""
